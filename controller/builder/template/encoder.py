import random
import argparse
import os

# =============================================================================
# ENCODERS
# =============================================================================

class Encoder:
    def encrypt(self, payload):
        raise NotImplementedError
    
    def get_c_definitions(self):
        raise NotImplementedError

class XorEncoder(Encoder):
    def __init__(self):
        self.key = [random.randint(0, 255), random.randint(0, 255)]
        self.encrypted = bytearray()

    def encrypt(self, payload):
        self.encrypted = bytearray()
        for i in range(len(payload)):
            self.encrypted.append(payload[i] ^ self.key[i % 2])
        return self.encrypted

    def get_c_definitions(self):
        return f"""
#define DECODER_XOR
#define PAYLOAD_LEN {len(self.encrypted)}
unsigned char XOR_KEY[2] = {{ 0x{self.key[0]:02X}, 0x{self.key[1]:02X} }};
unsigned char supermega_payload[] = {{
{format_c_array(self.encrypted)}
}};
"""

class EnglishEncoder(Encoder):
    def __init__(self):
        # deeply simplified english mapping (a=0, b=1, ...) for demo
        # a real one would use a dictionary
        self.encrypted = [] 
        self.map = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+/" # 64 chars
        
    def encrypt(self, payload):
        # Base64-ish but just mapping bytes to char sequences for "english-like" look?
        # User asked for "English mappings", let's do a simple word-based map for 1 byte -> 1 word
        # This is heavy but demonstrates the point.
        self.words = ["the", "be", "to", "of", "and", "a", "in", "that", "have", "i", 
                      "it", "for", "not", "on", "with", "he", "as", "you", "do", "at"]
        # Expand to 256 words for full coverage in a real impl
        while len(self.words) < 256:
            self.words.append(f"w{len(self.words)}")
            
        self.encrypted_str = ""
        for b in payload:
            self.encrypted_str += self.words[b] + " "
        return self.encrypted_str.encode('utf-8')

    def get_c_definitions(self):
        # We need the dictionary in C too
        dict_c = "const char* DICTIONARY[] = { " + ", ".join([f'"{w}"' for w in self.words]) + " };"
        
        # Payload is a string
        return f"""
#define DECODER_ENGLISH
#define PAYLOAD_LEN {len(self.words)} 
// Note: PAYLOAD_LEN here defines dictionary size, real payload size depends on string parsing
{dict_c}
char supermega_payload_str[] = "{self.encrypted_str.strip()}";
"""

def format_c_array(data):
    lines = []
    chunk_size = 12
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        hex_values = [f"0x{b:02X}" for b in chunk]
        lines.append("    " + ", ".join(hex_values) + ",")
    return "\n".join(lines)

# =============================================================================
# MAIN
# =============================================================================

def main():
    parser = argparse.ArgumentParser(description="Payload Encoder for SuperMega Integration")
    parser.add_argument("--input", help="Path to raw shellcode file (.bin)")
    parser.add_argument("--output", default="payload.h", help="Output C header file")
    parser.add_argument("--encoder", choices=["xor", "english"], default="xor", help="Encoding algorithm")
    args = parser.parse_args()

    # Input handling
    if args.input and os.path.exists(args.input):
        with open(args.input, "rb") as f:
            payload = f.read()
            print(f"[*] Loaded {len(payload)} bytes from {args.input}")
    else:
        print("[*] No input file provided, using dummy payload (NOPs + INT3)")
        payload = b"\x90" * 10 + b"\xCC" * 2

    # Encode
    encoder = None
    if args.encoder == "xor":
        encoder = XorEncoder()
    elif args.encoder == "english":
        encoder = EnglishEncoder()
    
    encoder.encrypt(payload) # Perform encryption

    # Generate Output
    content = f"""/* Auto-generated by encoder.py */
#ifndef PAYLOAD_H
#define PAYLOAD_H

{encoder.get_c_definitions()}

#endif
"""

    with open(args.output, "w") as f:
        f.write(content)
    
    print(f"[*] Generated {args.output} using {args.encoder} encoder")

if __name__ == "__main__":
    main()
