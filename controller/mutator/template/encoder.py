import random
import argparse
import os

def generate_xor_key():
    return [random.randint(0, 255), random.randint(0, 255)]

def encrypt_payload(payload_bytes, key):
    encrypted = bytearray()
    for i in range(len(payload_bytes)):
        encrypted.append(payload_bytes[i] ^ key[i % 2])
    return encrypted

def format_c_array(data):
    lines = []
    chunk_size = 12
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        hex_values = [f"0x{b:02X}" for b in chunk]
        lines.append("    " + ", ".join(hex_values) + ",")
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description="Payload Encoder for SuperMega Loader")
    parser.add_argument("--input", help="Path to raw shellcode file (.bin)")
    parser.add_argument("--output", default="payload.h", help="Output C header file")
    args = parser.parse_args()

    # Default dummy payload (NOPs + INT3) if no input provided
    if args.input and os.path.exists(args.input):
        with open(args.input, "rb") as f:
            payload = f.read()
            print(f"[*] Loaded {len(payload)} bytes from {args.input}")
    else:
        print("[*] No input file provided, using dummy payload (NOPs + INT3)")
        # Create a dummy payload of 272 bytes (similar to calc)
        payload = b"\x90" * 260 + b"\xCC" * 12

    search_key = generate_xor_key()
    encrypted_payload = encrypt_payload(payload, search_key)

    print(f"[*] Encrypting with key: 0x{search_key[0]:02X} 0x{search_key[1]:02X}")

    content = f"""/* Auto-generated by encoder.py */
#ifndef PAYLOAD_H
#define PAYLOAD_H

#define PAYLOAD_LEN {len(encrypted_payload)}

// Randomly generated 2-byte XOR key matching the payload
unsigned char XOR_KEY2[2] = {{ 0x{search_key[0]:02X}, 0x{search_key[1]:02X} }};

// Encrypted Payload
unsigned char supermega_payload[] = {{
{format_c_array(encrypted_payload)}
}};

#endif
"""

    with open(args.output, "w") as f:
        f.write(content)
    
    print(f"[*] Generated {args.output}")

if __name__ == "__main__":
    main()
